#!/usr/bin/env python3
"""Run the one authorised synthetic query case. No target application is used."""
import json
from pathlib import Path
import sqlite3


def main() -> None:
    database = sqlite3.connect(":memory:")
    try:
        database.executescript(Path(__file__).with_name("fixture.sql").read_text(encoding="utf-8"))
        database.execute("PRAGMA query_only = ON")
        rows = database.execute(
            "SELECT tenant_id, attempt_id FROM publishing_attempts WHERE tenant_id = :tenant_id ORDER BY attempt_id",
            {"tenant_id": 1},
        ).fetchall()
    finally:
        database.close()
    passed = rows == [(1, 10), (1, 11), (1, 12)]
    result = {
        "id": "ECRS001", "test_id": "ECTC001", "test_revision": "1",
        "status": "passed" if passed else "failed",
        "environment": "in-memory SQLite synthetic query fixture",
        "observed": f"Trusted tenant 1 query returned {rows}. No target application or authentication path was checked.",
        "source": "fixture-result.json, generated by run_fixture.py",
        "rows": rows,
    }
    print(json.dumps(result, indent=2))
    if not passed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
